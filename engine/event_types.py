import datetime
from dataclasses import dataclass, field
from typing import Optional

@dataclass
class Event:
    """Base class for all system events."""
    timestamp: datetime.datetime = field(default_factory=lambda: datetime.datetime.now(datetime.timezone.utc))

@dataclass
class MarketDataEvent(Event):
    """Event generated when new market data (OHLCV bar or tick) is ingested."""
    ticker: str = ""
    open_price: float = 0.0
    high_price: float = 0.0
    low_price: float = 0.0
    close_price: float = 0.0
    volume: float = 0.0
    vwap: Optional[float] = None
    trade_count: Optional[int] = None

@dataclass
class SignalEvent(Event):
    """Event generated by alpha models containing a trading signal."""
    ticker: str = ""
    signal_value: float = 0.0
    direction: str = "HOLD"  # "BUY", "SELL", "HOLD"
    conviction: float = 0.0   # Scale 0.0 to 1.0 (or 0 to 100)
    model_name: str = ""

@dataclass
class OrderEvent(Event):
    """Event representing an order request sent to the broker."""
    order_id: str = ""
    ticker: str = ""
    action: str = ""        # "BUY", "SELL"
    quantity: int = 0
    order_type: str = "MARKET"  # "MARKET", "LIMIT", "STOP"
    price: Optional[float] = None  # Limit price
    strategy_id: str = ""

@dataclass
class FillEvent(Event):
    """Event representing an execution confirmation (fill) from the broker."""
    order_id: str = ""
    ticker: str = ""
    action: str = ""        # "BUY", "SELL"
    quantity_filled: int = 0
    fill_price: float = 0.0
    commission: float = 0.0
    slippage: float = 0.0

@dataclass
class SystemStartedEvent(Event):
    """Event fired when the kernel starts up successfully."""
    env: str = ""

@dataclass
class SystemStoppedEvent(Event):
    """Event fired when the kernel is shutting down."""
    reason: str = "normal"

